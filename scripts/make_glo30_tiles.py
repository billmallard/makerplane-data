"""Regenerate packtools/data/glo30_tiles.txt, the Copernicus GLO-30 tiles
that exist inside any terrain region (TER-007's expected tile set).

Source: ``tileList.txt`` in the public Copernicus DEM bucket on AWS Open
Data (``s3://copernicus-dem-30m``), which lists every GLO-30 tile that
exists. Ocean cells have no tile, so this list is what lets TER-007 tell a
missing land tile from sea, which TER-002 cannot.

    python scripts/make_glo30_tiles.py             # fetch, check sha256, write
    python scripts/make_glo30_tiles.py --src FILE  # from a local copy

Only tiles whose SW corner falls inside a region in regions.yaml are kept,
so a new region needs a rerun. The output is sorted and deterministic.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE))

from packtools.regions import load_regions, tile_sw_corner  # noqa: E402

URL = "https://copernicus-dem-30m.s3.amazonaws.com/tileList.txt"
SHA256 = "10604e3052c98a09e9216f1a8f0a555a04148419757575f783d4937fd44316dc"
OUT = HERE / "packtools" / "data" / "glo30_tiles.txt"
_NAME = re.compile(r"^Copernicus_DSM_COG_10_([NS])(\d\d)_00_([EW])(\d\d\d)_00_DEM$")


def build(text: str) -> list[str]:
    regions = [r for k, r in load_regions().items() if k != "conus"]
    out = set()
    for line in text.splitlines():
        m = _NAME.match(line.strip())
        if not m:
            continue
        tile = f"{m[1]}{m[2]}{m[3]}{m[4]}"
        if any(r.contains(*tile_sw_corner(tile)) for r in regions):
            out.add(tile)
    return sorted(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", help="a local copy of tileList.txt")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    if a.src:
        raw = Path(a.src).read_bytes()
    else:
        req = urllib.request.Request(URL, headers={"User-Agent": "makerplane-data"})
        with urllib.request.urlopen(req, timeout=120) as r:
            raw = r.read()
    got = hashlib.sha256(raw).hexdigest()
    if got != SHA256:
        print(f"sha256 {got} is not the pinned {SHA256}", file=sys.stderr)
        return 1
    tiles = build(raw.decode("ascii"))
    head = (f"# Copernicus GLO-30 tiles inside the terrain regions of regions.yaml.\n"
            f"# source: {URL}\n# source sha256: {SHA256}\n"
            f"# generated by scripts/make_glo30_tiles.py; {len(tiles)} tiles\n")
    Path(a.out).write_text(head + "\n".join(tiles) + "\n", encoding="ascii")
    print(f"{len(tiles)} tiles -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
