"""Regenerate packtools/data/admin1_na.json, the state and province
boundaries the OSM per-state checks (OSM-002, OSM-006) bin features by.

Source: Natural Earth 1:10m Admin 1 -- States, Provinces, v5.1.2 (public
domain, https://www.naturalearthdata.com/about/terms-of-use/), the US,
Canada and Mexico features only. Each ring is simplified (Douglas-Peucker,
SIMPLIFY_DEG) and rounded to ROUND decimals, which keeps the file small;
the checks only need to tell which state a feature's centre is in, and
the same file bins both editions of a comparison, so a border error moves
nothing between them.

    python scripts/make_admin1.py            # fetch, check sha256, write
    python scripts/make_admin1.py --src FILE # from a local copy

The output is deterministic: rerunning on the same input writes the same
bytes. A change to this file changes OSM-002/OSM-006 counts; the next
record's delta then compares against a record binned with the old file,
so land it with a note (docs/pack_report.md, "OSM-002 and OSM-006").
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import urllib.request
from pathlib import Path

URL = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/"
       "geojson/ne_10m_admin_1_states_provinces.geojson")
SHA256 = "22d0e3ad85eb3e27f17cabf8ba2d50e554fbc27a87796ff891d958185da62fb5"
COUNTRIES = ("USA", "CAN", "MEX")
SIMPLIFY_DEG = 0.01
ROUND = 3
OUT = Path(__file__).resolve().parent.parent / "packtools" / "data" / "admin1_na.json"


def _dp(pts, tol):
    """Douglas-Peucker on a list of (lon, lat), iterative."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        norm = (dx * dx + dy * dy) ** 0.5
        best, idx = -1.0, -1
        for i in range(a + 1, b):
            x, y = pts[i]
            d = (abs(dy * x - dx * y + x2 * y1 - y2 * x1) / norm if norm
                 else ((x - x1) ** 2 + (y - y1) ** 2) ** 0.5)
            if d > best:
                best, idx = d, i
        if idx >= 0 and best > tol:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]


def _ring(coords):
    pts = _dp([(float(x), float(y)) for x, y in coords], SIMPLIFY_DEG)
    out = []
    for x, y in pts:
        q = [round(x, ROUND), round(y, ROUND)]
        if not out or out[-1] != q:
            out.append(q)
    return out if len(out) >= 4 else None


def build(raw: bytes) -> dict:
    data = json.loads(raw)
    regions = []
    for f in data["features"]:
        p = f["properties"]
        if p["adm0_a3"] not in COUNTRIES:
            continue
        g = f["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        rings = [r for poly in polys for r in (_ring(c) for c in poly) if r]
        if not rings:
            continue
        regions.append({"code": p["iso_3166_2"], "name": p["name"],
                        "country": p["adm0_a3"], "rings": rings})
    regions.sort(key=lambda r: r["code"])
    return {
        "source": "Natural Earth 1:10m Admin 1 -- States, Provinces, v5.1.2 (public domain)",
        "source_url": URL,
        "source_sha256": SHA256,
        "simplify_deg": SIMPLIFY_DEG,
        "note": "rings are [lon, lat]; even-odd fill; generated by scripts/make_admin1.py",
        "regions": regions,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", help="a local copy of the Natural Earth GeoJSON")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    if a.src:
        raw = Path(a.src).read_bytes()
    else:
        req = urllib.request.Request(URL, headers={"User-Agent": "makerplane-data"})
        with urllib.request.urlopen(req, timeout=300) as r:
            raw = r.read()
    got = hashlib.sha256(raw).hexdigest()
    if got != SHA256:
        print(f"sha256 {got} is not the pinned {SHA256}", file=sys.stderr)
        return 1
    out = build(raw)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(out, separators=(",", ":"), sort_keys=True) + "\n",
                           encoding="utf-8")
    n = sum(len(r) for reg in out["regions"] for r in reg["rings"])
    print(f"{len(out['regions'])} regions, {n:,} vertices -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
