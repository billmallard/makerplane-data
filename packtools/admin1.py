"""States and provinces for the OSM per-state checks (OSM-002, OSM-006).

The boundaries are Natural Earth 1:10m Admin 1 (public domain), US,
Canada and Mexico, simplified to about 1 km (``packtools/data/admin1_na.json``,
regenerated by ``scripts/make_admin1.py``).

Features are binned by the centre of their bounding box, in two steps so
the work stays in SQLite: features are first grouped into CELL_DEG cells,
then each occupied cell's centre is placed in a state. A feature near a
border can land in the neighbour; both editions of a comparison are binned
the same way, so that moves nothing between them. A cell centre in no
state (Natural Earth leaves bays and estuaries out of the land polygons,
and simplification trims coasts) takes the first state found at up to
NEAR_DEG around it, in a fixed order; one still in none (offshore, or
outside the three countries) is binned as OUTSIDE.

Lengths and areas are on a local flat-earth approximation (good to well
under 1 % at feature scale), from the pack's own vertex blobs:
``highway_lines.verts`` and ``waterway_lines.verts`` are little-endian
float32 (lat, lon) pairs (pyEfis ``ai/highway_db.py``);
``water_polygons.vertices`` is little-endian float64 (lat, lon) pairs, with
``rings`` the ring END offsets (uint16, or uint32 past 65,535 vertices)
when the polygon has holes (pyEfis ``tools/build_water_db.py``). A blob
whose length is not a whole number of vertex pairs is measured on its
whole pairs only: these checks compare totals, they do not judge blobs.
"""

from __future__ import annotations

import array
import json
import math
import sqlite3
import sys
from functools import lru_cache
from pathlib import Path

DATA = Path(__file__).resolve().parent / "data" / "admin1_na.json"
CELL_DEG = 0.05
NEAR_DEG = 0.1
OUTSIDE = "outside"
KM_PER_DEG = 111.195

#: Per-state measure for each OSM table: (what, SQL function, its arguments).
MEASURES = {
    "highway_lines": ("length_km", "vlen32", "verts"),
    "waterway_lines": ("length_km", "vlen32", "verts"),
    "water_polygons": ("area_km2", "varea64", "vertices, rings"),
}


@lru_cache(maxsize=2)
def load(path: str | None = None) -> dict:
    data = json.loads(Path(path or DATA).read_text(encoding="utf-8"))
    for r in data["regions"]:
        xs = [x for ring in r["rings"] for x, _ in ring]
        ys = [y for ring in r["rings"] for _, y in ring]
        r["bbox"] = (min(xs), min(ys), max(xs), max(ys))
    return data


def _inside(rings, x: float, y: float) -> bool:
    """Even-odd point-in-polygon over every ring of a region."""
    hit = False
    for ring in rings:
        j = len(ring) - 1
        for i in range(len(ring)):
            xi, yi = ring[i]
            xj, yj = ring[j]
            if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
                hit = not hit
            j = i
    return hit


def locate(lat: float, lon: float, path: str | None = None) -> str:
    """The ISO 3166-2 code of the state or province holding the point, or OUTSIDE."""
    for r in load(path)["regions"]:
        x0, y0, x1, y1 = r["bbox"]
        if x0 <= lon <= x1 and y0 <= lat <= y1 and _inside(r["rings"], lon, lat):
            return r["code"]
    return OUTSIDE


def locate_near(lat: float, lon: float, path: str | None = None) -> str:
    """``locate``, falling back to the nearest state within NEAR_DEG."""
    code = locate(lat, lon, path)
    steps = int(round(NEAR_DEG / CELL_DEG))
    for k in range(1, steps + 1):
        if code != OUTSIDE:
            break
        d = k * CELL_DEG
        for dy, dx in ((0, -d), (0, d), (-d, 0), (d, 0), (-d, -d), (-d, d), (d, -d), (d, d)):
            code = locate(lat + dy, lon + dx, path)
            if code != OUTSIDE:
                break
    return code


def names(path: str | None = None) -> dict[str, str]:
    return {r["code"]: r["name"] for r in load(path)["regions"]}


# --- geometry measures (registered as SQLite functions) ---------------------

def vlen32(blob) -> float:
    """Polyline length in km from a float32 (lat, lon) blob."""
    if not blob:
        return 0.0
    a = array.array("f")
    a.frombytes(blob[:len(blob) - len(blob) % 8])
    if sys.byteorder == "big":
        a.byteswap()
    km = 0.0
    for i in range(2, len(a) - 1, 2):
        dy = a[i] - a[i - 2]
        dx = (a[i + 1] - a[i - 1]) * math.cos(math.radians((a[i] + a[i - 2]) / 2))
        km += math.hypot(dx, dy)
    return km * KM_PER_DEG


def _ring_area(a, lo: int, hi: int) -> float:
    """|shoelace| of vertices lo..hi-1 (a flat (lat, lon) array), km^2."""
    n = hi - lo
    if n < 3:
        return 0.0
    k = math.cos(math.radians(sum(a[2 * i] for i in range(lo, hi)) / n))
    s = 0.0
    for i in range(lo, hi):
        j = lo if i == hi - 1 else i + 1
        s += a[2 * i + 1] * a[2 * j] - a[2 * j + 1] * a[2 * i]
    return abs(s) / 2 * k * KM_PER_DEG * KM_PER_DEG


def varea64(blob, rings=None) -> float:
    """Polygon area in km^2 from a float64 (lat, lon) blob: the outer ring
    less its holes."""
    if not blob:
        return 0.0
    a = array.array("d")
    a.frombytes(blob[:len(blob) - len(blob) % 16])
    if sys.byteorder == "big":
        a.byteswap()
    n = len(a) // 2
    ends = [n]
    if rings:
        ends = array.array("H" if n <= 65535 else "I")
        ends.frombytes(rings[:len(rings) - len(rings) % ends.itemsize])
        if sys.byteorder == "big":
            ends.byteswap()
        ends = [e for e in ends if 0 < e <= n] or [n]
    starts = [0] + ends[:-1]
    areas = [_ring_area(a, s, e) for s, e in zip(starts, ends)]
    return max(0.0, areas[0] - sum(areas[1:]))


def register(con: sqlite3.Connection) -> None:
    con.create_function("vlen32", 1, vlen32, deterministic=True)
    con.create_function("varea64", 2, varea64, deterministic=True)


# --- per-state binning ------------------------------------------------------

def per_state(con: sqlite3.Connection, table: str, *, measure: bool = True,
              path: str | None = None) -> dict[str, dict]:
    """``{state: {"features": n, <length_km|area_km2>: x}}`` for one table
    with a min/max lat/lon bounding box. ``measure=False`` skips the
    vertex decode and returns counts only."""
    spec = MEASURES.get(table) if measure else None
    agg = f", SUM({spec[1]}({spec[2]}))" if spec else ""
    if spec:
        register(con)
    rows = con.execute(
        f"SELECT CAST(((min_lat + max_lat) / 2.0 + 90) / {CELL_DEG} AS INTEGER) AS cy, "
        f"CAST(((min_lon + max_lon) / 2.0 + 180) / {CELL_DEG} AS INTEGER) AS cx, "
        f'COUNT(*){agg} FROM "{table}" WHERE min_lat IS NOT NULL AND min_lon IS NOT NULL '
        f"GROUP BY cy, cx").fetchall()
    out: dict[str, dict] = {}
    for cy, cx, n, *rest in rows:
        lat = (cy + 0.5) * CELL_DEG - 90
        lon = (cx + 0.5) * CELL_DEG - 180
        st = out.setdefault(locate_near(lat, lon, path), {"features": 0})
        st["features"] += n
        if spec:
            st[spec[0]] = st.get(spec[0], 0.0) + (rest[0] or 0.0)
    for st in out.values():
        for k in ("length_km", "area_km2"):
            if k in st:
                st[k] = round(st[k], 1)
    return dict(sorted(out.items()))
